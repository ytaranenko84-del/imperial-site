const payload = await getPayload({ config })
let updated = 0
let missing = 0

for (const item of RU) {
  const found = await payload.find({
    collection: 'news', where: { slug: { equals: item.slug } }, limit: 1, overrideAccess: true,
  })
  if (!found.docs.length) { console.log(`не знайдено: ${item.slug}`); missing++; continue }
  await payload.update({
    collection: 'news', id: found.docs[0].id, locale: 'ru', overrideAccess: true,
    data: { title: item.title, term: item.term, lead: item.lead, body: item.body },
  })
  updated++
}

console.log(`перекладено: ${updated}, не знайдено: ${missing}`)
