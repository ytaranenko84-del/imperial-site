const payload = await getPayload({ config })
let created = 0
let updated = 0

for (const item of ITEMS) {
  const found = await payload.find({
    collection: 'news', where: { slug: { equals: item.slug } }, limit: 1, overrideAccess: true,
  })
  if (found.docs.length) {
    await payload.update({ collection: 'news', id: found.docs[0].id, data: item, overrideAccess: true })
    updated++
  } else {
    await payload.create({ collection: 'news', data: item, overrideAccess: true })
    created++
  }
}

const all = await payload.find({ collection: 'news', limit: 100, overrideAccess: true })
console.log(`перенесено: створено ${created}, оновлено ${updated}, усього в базі ${all.totalDocs}`)
